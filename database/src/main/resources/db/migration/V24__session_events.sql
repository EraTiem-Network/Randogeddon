-- What happens on a session's game server (Phase 19), as the gateway hears it: the packets the tracker makes the
-- live feed and the slots' presence of (kind 'packet'), and the game server's starts and ends ('start', 'stop').
-- The tracker reads them from here by their order (id), so nothing is lost while it isn't connected. By the
-- session's public ID; deleted with the session.
CREATE TABLE session_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session varchar(40) NOT NULL,
  at_ms bigint NOT NULL,
  kind varchar(8) NOT NULL,
  packet text NOT NULL
);
CREATE INDEX session_events_by_session ON session_events (session, id);
