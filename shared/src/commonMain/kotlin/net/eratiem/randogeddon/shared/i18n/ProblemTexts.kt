/** The server's refusals, worded: every [Problem] with its values ([args], by name). */
interface ProblemTexts {
  fun text(problem: Problem, args: Map<String, String>): String

  /** What the tracker says on the dashboard while it can't follow the game server ([refused]: it was turned away). */
  fun trackerError(refused: Boolean, detail: String): String
}

fun ProblemTexts.text(refusal: Refusal): String = text(refusal.problem, refusal.args)

/** The value [key] of [args]; empty if it's missing (a text never fails over it). */
private fun Map<String, String>.v(key: String): String = this[key].orEmpty()

/** Roles named in a list (`manager,support`), worded by [people]. */
private fun roles(people: PeopleTexts, codes: String, or: String): String =
  codes.split(',').mapNotNull { code -> SessionRole.entries.firstOrNull { it.code == code } }
    .joinToString(" $or ") { people.role(it) }

private fun action(cheats: CheatTexts, name: String): String =
  CheatAction.entries.firstOrNull { it.name == name }?.let { cheats.action(it) } ?: name

