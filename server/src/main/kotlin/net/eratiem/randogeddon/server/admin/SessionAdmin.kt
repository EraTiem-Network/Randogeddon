private val logger = logger(MethodHandles.lookup().lookupClass())

/** The World Locks slot's name in a seed made in the admin panel (gateway/.../Archipelago.kt, locksYaml). */
private const val LOCKS_SLOT = "Locks"

/** A request the admin panel can't carry out, with what to tell the admin. */
class SessionProblem(val status: HttpStatusCode, message: String) : Exception(message)

/**
 * Creating and deleting sessions in the admin panel: one at a time. A new session's seed is generated by the gateway;
 * then its players get logins (new ones shown once), its slots their players and slot passwords, and the game server
 * starts on it. A finished session makes way for a new one (it is archived and stays a past session); a running one
 * has to be finished or deleted first. Deleting keeps the logins: they belong to people, who will play again.
 */
@Single
class SessionAdmin(
  private val config: TrackerConfig,
  private val gameServer: GameServerClient,
  private val users: UserStore,
  private val setups: SessionSetupStore,
  private val slotPasswords: SlotPasswordStore,
  private val session: CurrentSession,
  private val tracker: TrackerService,
  private val finishes: SessionFinishStore,
  private val archives: Archives,
  private val spoilers: Spoilers,
) {
  suspend fun view(): AdminSessionView {
    val seed = Room.read(config.roomJson)?.seedName
    val setup = seed?.let { setups.of(it) }
    val finish = seed?.let { finishes.of(it) }
    val info = when {
      setup != null -> SessionInfo(
        seedName = setup.seedName,
        apVersion = setup.apVersion,
        createdAt = setup.createdAt.toEpochMilli(),
        options = setup.options?.let { runCatching { ApiJson.decodeFromString(SessionOptions.serializer(), it) }.getOrNull() },
        worlds = setup.worlds.map { (slot, names) -> WorldPlan(slot, names) },
      )
      // A seed deployed with the CLI: its people come from session.yaml
      seed != null -> SessionInfo(seedName = seed, worlds = session.people().flatMap { (person, slots) ->
        slots.map { it to person }
      }.groupBy({ it.first }, { it.second }).map { (slot, names) -> WorldPlan(slot, names) })
      else -> null
    }?.let { i ->
      val finishedAt = finish?.finishedAt
      i.copy(
        finishesAt = finish?.dueAt?.toEpochMilli(),
        finishedAt = finishedAt?.toEpochMilli(),
        reopenUntil = finishedAt?.let { reopenUntil(it, completed(archives.read(i.seedName)?.summary?.totals?.percent))?.toEpochMilli() },
        keep = finish?.keep == true,
        deletesAt = finishedAt?.let { deletesAt(it, finish.keep, config.sessionRetentionDays, finish.retainedSince)?.toEpochMilli() },
        // Pause (not complete) or end (complete): how far it got
        percent = archives.read(i.seedName)?.summary?.totals?.percent?.takeIf { finishedAt != null }
          ?: tracker.read { summary(config.title, null).totals.percent },
      )
    }
    return AdminSessionView(
      session = info,
      apVersions = runCatching { gameServer.versions() }.getOrDefault(emptyList()),
      users = users.active().map { it.name }.sorted(),
    )
  }

  /**
   * The slots of the YAMLs and what's wrong with them, including games the release has no apworld for. If the gateway
   * can't list the release's games, that check is left to Generate.py.
   */
  suspend fun inspect(request: InspectRequest): InspectResult {
    val inspected = PlayerYamls.inspect(request.yamls)
    val release = runCatching { gameServer.archipelago() }.getOrNull()?.releases?.let { releases ->
      releases.firstOrNull { it.version == request.apVersion } ?: releases.firstOrNull().takeIf { request.apVersion == null }
    }
    if (release == null || release.error != null) return inspected
    val missing = PlayerYamls.missingGames(inspected.worlds, release.games.map { it.game }.toSet())
    return inspected.copy(problems = inspected.problems + missing.map { game ->
      "No APWorld for $game in Archipelago ${release.version}: upload it under APWorlds"
    })
  }

  suspend fun create(request: CreateSessionRequest, admin: String): CreateSessionResult {
    val current = Room.read(config.roomJson)?.seedName
    val finished = current != null && finishes.of(current)?.finishedAt != null
    if (!finished && gameServer.state().status != GameServerStatus.NO_SEED) {
      throw SessionProblem(HttpStatusCode.Conflict, "There is a session already; finish or delete it first")
    }
    val inspected = inspect(InspectRequest(request.yamls, request.apVersion))
    if (inspected.problems.isNotEmpty()) throw SessionProblem(HttpStatusCode.BadRequest, inspected.problems.joinToString("\n"))
    if (inspected.worlds.isEmpty()) throw SessionProblem(HttpStatusCode.BadRequest, "No slots: upload the player YAMLs")
    val names = inspected.worlds.map { it.name }.toSet()
    request.worlds.map { it.name }.filter { it !in names }.takeIf { it.isNotEmpty() }?.let {
      throw SessionProblem(HttpStatusCode.BadRequest, "Not in the YAMLs: ${it.joinToString()}")
    }
    val plans = inspected.worlds.associate { world -> world.name to (request.worlds.firstOrNull { it.name == world.name } ?: WorldPlan(world.name)) }
    val people = plans.values.flatMap { it.users }.map { it.trim() }.filter { it.isNotEmpty() }.distinctBy { it.lowercase() }
    people.firstOrNull { it.length > 64 }?.let { throw SessionProblem(HttpStatusCode.BadRequest, "Name too long: $it") }
    val versions = gameServer.versions()
    val version = request.apVersion ?: versions.firstOrNull()
      ?: throw SessionProblem(HttpStatusCode.ServiceUnavailable, "The gateway has no Archipelago release")
    if (version !in versions) {
      throw SessionProblem(HttpStatusCode.BadRequest, "Archipelago $version isn't supported here (${versions.joinToString()})")
    }

    val locked = when (val open = request.options.openSlots) {
      null -> plans.values.filter { it.locked }.map { it.name }
      else -> if (plans.values.any { it.random }) pickMixed(plans.values.toList(), open, random) else pickLocked(plans.keys.toList(), open, random)
    }
    // Someone has to start: the keys are found in the open slots
    if (locked.size >= plans.size) throw SessionProblem(HttpStatusCode.BadRequest, "At least one slot has to start open")
    logger.info("{} creates a session: {} slots, {} players, Archipelago {}", admin, plans.size, people.size, version)
    val games = inspected.worlds.flatMap { it.game.split(" / ") }.distinct()
    if (finished) {
      // The finished session becomes a past one: its files go to the gateway's archive
      gameServer.archiveSession()
      tracker.clear()
      logger.info("Session {} is archived", current)
    }
    val generated = gameServer.generate(GenerateRequest(request.yamls, locked, request.options.earlyKeys, version, games))
    val seed = generated.seedName ?: throw SessionProblem(HttpStatusCode.UnprocessableEntity, failure(generated))

    // People without a login get one now; its password is shown once, in the answer
    val logins = mutableListOf<NewLogin>()
    val ids = people.associate { name ->
      val user = users.findActive(name) ?: PasswordGenerator.generate().let { password ->
        logins += NewLogin(name, password)
        users.create(name, PasswordHasher.hash(password))
      }
      name.lowercase() to user.id
    }
    setups.create(
      seed, version, ApiJson.encodeToString(SessionOptions.serializer(), request.options),
      plans.mapValues { (_, plan) -> plan.users.mapNotNull { ids[it.trim().lowercase()] } },
    )
    slotPasswords.ensure(seed, plans.keys + listOfNotNull(LOCKS_SLOT.takeIf { locked.isNotEmpty() }), { PasswordGenerator.generate() })
    gameServer.control("restart")
    session.refresh()
    logger.info("{} created session {} ({} new logins)", admin, seed, logins.size)
    return CreateSessionResult(seed, logins, locked)
  }

  /** For the random locks. */
  private val random: Random = SecureRandom().asKotlinRandom()

  /** Stops the game server, moves the seed and its save away (data/old), removes the session; the logins stay. */
  suspend fun delete(admin: String) {
    val seed = Room.read(config.roomJson)?.seedName
    gameServer.deleteSession()
    seed?.let { forget(it) }
    tracker.clear()
    session.refresh()
    logger.info("{} deleted session {}", admin, seed ?: "(no seed)")
  }

  /** Deletes a past session for good: its files, its archive, its setup; the logins stay. */
  suspend fun deletePast(seed: String, admin: String) {
    if (seed == Room.read(config.roomJson)?.seedName) {
      throw SessionProblem(HttpStatusCode.Conflict, "$seed is the current session; delete it there")
    }
    if (finishes.of(seed)?.finishedAt == null) throw SessionProblem(HttpStatusCode.NotFound, "No past session $seed")
    gameServer.deleteArchived(seed)
    forget(seed)
    logger.info("{} deleted past session {}", admin, seed)
  }

  /**
   * Deletes the past sessions whose time has come ([TrackerConfig.sessionRetentionDays] after they finished, or after
   * their auto-deletion was enabled again), unless their auto-deletion is disabled; the current seed stays. Once an hour, for as long as [scope] runs.
   */
  fun cleanUp(scope: CoroutineScope) = scope.launch {
    while (true) {
      runCatching {
        val now = Instant.now()
        val current = Room.read(config.roomJson)?.seedName
        finishes.finished().filter { it.seedName != current }.forEach { f ->
          val due = deletesAt(f.finishedAt, f.keep, config.sessionRetentionDays, f.retainedSince)
          if (due != null && now.isAfter(due)) deletePast(f.seedName, "auto-deletion")
        }
      }.onFailure { logger.warn("Could not delete old sessions: {}", it.message) }
      delay(1.hours)
    }
  }

  /** [keep] disables the session's auto-deletion; deleting it by hand stays possible. */
  suspend fun setKeep(seed: String, keep: Boolean, admin: String) {
    if (!finishes.setKeep(seed, keep)) throw SessionProblem(HttpStatusCode.NotFound, "No session $seed")
    session.refresh()
    logger.info("{} {} the auto-deletion of {}", admin, if (keep) "disabled" else "enabled", seed)
  }

  private suspend fun forget(seed: String) {
    setups.delete(seed)
    archives.delete(seed)
    spoilers.forget(seed)
  }
}

/**
 * Random locks: [open] of the slots, picked at random, start open; the others are locked. At least one has to be
 * open (or no key could ever be found), and there must be something to lock.
 */
internal fun pickLocked(slots: List<String>, open: Int, random: Random): List<String> {
  if (slots.size < 2) throw SessionProblem(HttpStatusCode.BadRequest, "Random locks need at least 2 slots")
  if (open < 1) throw SessionProblem(HttpStatusCode.BadRequest, "At least one slot has to start open")
  if (open >= slots.size) {
    throw SessionProblem(HttpStatusCode.BadRequest, "With ${slots.size} slots, at most ${slots.size - 1} can start open for random locks")
  }
  val openSlots = slots.shuffled(random).take(open).toSet()
  return slots.filter { it !in openSlots }
}

/**
 * Mixed locks: the slots that aren't [WorldPlan.random] start open or locked as they say; of the random ones, as many
 * start open as make [open] in all, picked at random, and the rest are locked. At least one slot starts open.
 */
internal fun pickMixed(plans: List<WorldPlan>, open: Int, random: Random): List<String> {
  val sure = plans.count { !it.random && !it.locked }
  val pool = plans.filter { it.random }.map { it.name }
  val least = maxOf(1, sure)
  if (open < least || open > sure + pool.size) {
    throw SessionProblem(
      HttpStatusCode.BadRequest,
      "With $sure slots open for sure and ${pool.size} left to chance, between $least and ${sure + pool.size} can start open",
    )
  }
  val picked = pool.shuffled(random).take(open - sure).toSet()
  return plans.filter { if (it.random) it.name !in picked else it.locked }.map { it.name }
}

/** What to tell the admin when Generate.py made no seed: the games that may be the cause, then its output. */
internal fun failure(result: GenerateResult): String = buildString {
  if (result.suspects.isEmpty()) {
    append("Generation failed. Perhaps a game isn't supported by this Archipelago release, or a YAML has an option ")
    append("it doesn't know. Generate.py said:")
  } else {
    append("Generation failed, possibly because of:")
    result.suspects.forEach { s ->
      append("\n• ${s.game}")
      val file = listOfNotNull(s.apworld?.let { "APWorld $it" }, s.from?.let { "from Archipelago $it" })
      if (file.isNotEmpty()) append(" (${file.joinToString(", ")})")
      append(": ${s.reason}")
    }
    append("\n\nGenerate.py said:")
  }
  result.log.forEach { append("\n").append(it) }
}
